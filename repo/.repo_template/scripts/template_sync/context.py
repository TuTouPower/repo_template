class SyncError(Exception):
    pass


@dataclass(frozen=True)
class SyncContext:
    """不可变同步身份：消费仓根、全部派生路径与本次覆盖。

    唯一真相源：所有 helper/action/CLI 只接受显式传入的本对象。
    ``source_override`` / ``checkout_override`` 替代历史模块级可变状态，
    仅由 CLI 入口按本次命令行参数构造，日常 helper 不得自行回退。
    """

    consumer: Path
    state_path: Path
    skills_src: Path
    skills_agents: Path
    skills_claude: Path
    commands_opencode: Path
    conventions_path: Path
    source_override: str | None = None
    checkout_override: Path | None = None

    @classmethod
    def for_consumer(
        cls,
        consumer: Path,
        *,
        source_override: str | None = None,
        checkout_override: Path | str | None = None,
    ) -> SyncContext:
        root = consumer.expanduser().resolve()
        checkout: Path | None = None
        if checkout_override is not None:
            checkout = Path(checkout_override).expanduser().resolve()
        return cls(
            consumer=root,
            state_path=common_state_dir(root) / "sync_state.json",
            skills_src=root / ".repo_template/skills",
            skills_agents=root / ".agents/skills",
            skills_claude=root / ".claude/skills",
            commands_opencode=root / ".opencode/commands",
            conventions_path=root / "docs/blueprint/conventions.md",
            source_override=source_override,
            checkout_override=checkout,
        )

    def rel(self, path: Path) -> str:
        try:
            return path.relative_to(self.consumer).as_posix()
        except ValueError:
            return path.as_posix()

    def contains(self, path: Path) -> bool:
        """路径（含软链解析后）是否仍在消费仓内；迁移写盘前统一边界校验。"""
        return path.resolve(strict=False).is_relative_to(self.consumer.resolve())

    def legacy_state_path(self) -> Path:
        return self.consumer / ".agents/skills/repo-template-sync/sync_state.json"
