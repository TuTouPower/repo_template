def _ensure_symlink(link: Path, target_rel: str, expected: Path, changed: set[Path], reports: list[str]) -> None:
    if link.is_symlink():
        if link.resolve() == expected:
            return
        _stage_rollback(link)
        link.unlink()
        os.symlink(target_rel, link)
        changed.add(link)
        return
    if link.is_dir():
        # 旧架构残留：宿主位曾是模板同步进去的真实目录。新架构真相源收敛到
        # .repo_template/skills/，宿主位只留软链。备份旧内容后转软链。
        _stage_rollback(link)
        shutil.rmtree(link)
        os.symlink(target_rel, link)
        changed.add(link)
        reports.append(f"{_rel(link)} 旧真实目录已转软链（原内容入回滚栈）")
        return
    if link.exists():
        reports.append(f"{_rel(link)} 非本机制管理，跳过")
        return
    link.parent.mkdir(parents=True, exist_ok=True)
    os.symlink(target_rel, link)
    changed.add(link)


_RETIRED_MERGE_GUARD_COMMAND = 'python3 "$CLAUDE_PROJECT_DIR/.claude/hooks/merge_guard.py"'


def _detect_json_indent(raw: str) -> int | str:
    """从现有 JSON 文本推断缩进（首个 ^(空格|tab)+\" 行），无匹配回退 2。

    同步改写消费仓 JSON（settings.json / MCP）时沿用原缩进，避免把消费仓
    4 空格体例重排成 2 空格、反而弄红其 prettier 门禁。
    """
    for line in raw.splitlines():
        if not line or line[0] not in (" ", "\t"):
            continue
        stripped = line.lstrip(" \t")
        if stripped.startswith('"'):
            prefix = line[: len(line) - len(stripped)]
            if set(prefix) == {"\t"}:
                return "\t"
            if set(prefix) == {" "}:
                return len(prefix)
    return 2


def _remove_retired_merge_guard_setting(changed: set[Path], reports: list[str]) -> None:
    settings = CONSUMER / ".claude/settings.json"
    if not settings.is_file():
        return
    try:
        raw = settings.read_text(encoding="utf-8")
        data = json.loads(raw)
    except (json.JSONDecodeError, UnicodeDecodeError, OSError) as error:
        raise SyncError(
            f"{_rel(settings)} 无法解析，不能安全移除已退役 merge guard PreToolUse（{error}）"
        ) from error
    hooks = data.get("hooks")
    if not isinstance(hooks, dict):
        return
    groups = hooks.get("PreToolUse")
    if not isinstance(groups, list):
        return
    changed_settings = False
    kept_groups = []
    for group in groups:
        if not isinstance(group, dict):
            kept_groups.append(group)
            continue
        entries = group.get("hooks")
        if not isinstance(entries, list):
            kept_groups.append(group)
            continue
        kept_entries = [
            entry for entry in entries
            if not (
                isinstance(entry, dict)
                and str(entry.get("command", "")).strip() == _RETIRED_MERGE_GUARD_COMMAND
            )
        ]
        if len(kept_entries) != len(entries):
            changed_settings = True
        if kept_entries:
            updated = dict(group)
            updated["hooks"] = kept_entries
            kept_groups.append(updated)
    if not changed_settings:
        return
    _stage_rollback(settings)
    if kept_groups:
        hooks["PreToolUse"] = kept_groups
    else:
        hooks.pop("PreToolUse", None)
    if not hooks:
        data.pop("hooks", None)
    temporary = settings.with_name(settings.name + ".tmp")
    temporary.write_text(json.dumps(data, ensure_ascii=False, indent=_detect_json_indent(raw)) + "\n", encoding="utf-8")
    temporary.replace(settings)
    changed.add(settings)
    reports.append(f"{_rel(settings)} 已移除退役 merge guard PreToolUse")


def repair_symlinks(changed: set[Path]) -> list[str]:
    """建/修宿主软链，指向 .repo_template/。非本机制链接报告不碰。"""
    reports: list[str] = []
    if SKILLS_SRC.exists():
        for entry in SKILLS_SRC.iterdir():
            if not entry.is_dir():
                continue
            expected = entry.resolve()
            _ensure_symlink(
                SKILLS_CLAUDE / entry.name,
                os.path.join("..", "..", ".repo_template", "skills", entry.name),
                expected, changed, reports,
            )
            _ensure_symlink(
                SKILLS_AGENTS / entry.name,
                os.path.join("..", "..", ".repo_template", "skills", entry.name),
                expected, changed, reports,
            )
    legacy_guard = CONSUMER / ".claude/hooks/merge_guard.py"
    retired_target = CONSUMER / ".repo_template/hooks/merge_guard.py"
    managed_retired_guard = (
        legacy_guard.is_symlink()
        and legacy_guard.resolve(strict=False) == retired_target.resolve(strict=False)
    )
    guard_missing = not legacy_guard.exists() and not legacy_guard.is_symlink()
    if managed_retired_guard or guard_missing:
        _remove_retired_merge_guard_setting(changed, reports)
    if managed_retired_guard:
        _stage_rollback(legacy_guard)
        legacy_guard.unlink()
        changed.add(legacy_guard)
        reports.append(f"{_rel(legacy_guard)} 已退役并移除")
    return reports


def _skill_description(skill_dir: Path, name: str) -> str:
    """读 SKILL.md frontmatter 的 description；缺失/无意义时回退。"""
    desc = f"Run {name} skill"
    try:
        text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    except OSError:
        return desc
    if text.startswith("---"):
        end = text.find("---", 3)
        if end != -1:
            for line in text[3:end].splitlines():
                if line.startswith("description:"):
                    desc = line.split(":", 1)[1].strip()
                    break
    if not desc or desc.lower() == "none":
        desc = f"Run {name} skill"
    return desc.replace('"', "'")


def sync_opencode_commands(changed: set[Path]) -> list[str]:
    """项目级 opencode 命令薄层：每个 skill 生成同名 /<skill> 命令。

    opencode 能直接识别 .agents/skills，但缺 / 触发器。命令正文只做一件事：
    让 agent 经 skill 工具加载执行对应 skill，$ARGUMENTS 透传。description
    取自 SKILL.md frontmatter（SKILL.md 是唯一真相源）。
    手写命令（无本机制标记）永不覆盖/删除；skill 删除后仅清理带标记残留。
    """
    reports: list[str] = []
    if not SKILLS_SRC.exists():
        return reports
    COMMANDS_OPENCODE.mkdir(parents=True, exist_ok=True)
    names = sorted(e.name for e in SKILLS_SRC.iterdir() if e.is_dir())
    for name in names:
        content = (
            "---\n"
            f'description: "{_skill_description(SKILLS_SRC / name, name)}"\n'
            "---\n"
            f"> {COMMAND_MARKER} '{name}'. Do not edit directly.\n\n"
            f"Load and execute the `{name}` skill via the `skill` tool, "
            "following its SKILL.md instructions.\n\n"
            "User arguments: $ARGUMENTS\n"
        )
        dest = COMMANDS_OPENCODE / f"{name}.md"
        if dest.exists() and not dest.is_file():
            continue
        if dest.is_file():
            existing = dest.read_text(encoding="utf-8")
            if existing == content:
                continue
            if COMMAND_MARKER not in existing:
                reports.append(f"{_rel(dest)} 疑似手写命令（与 skill 同名），跳过")
                continue
        _stage_rollback(dest)
        dest.write_text(content, encoding="utf-8")
        changed.add(dest)
    for md in COMMANDS_OPENCODE.glob("*.md"):
        if md.stem in names:
            continue
        try:
            if COMMAND_MARKER in md.read_text(encoding="utf-8"):
                _stage_rollback(md)
                md.unlink()
                changed.add(md)
        except OSError:
            continue
    return reports


