def _md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["------"] * len(headers)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def cmd_plan(args: argparse.Namespace) -> int:
    state = read_state()
    if not state:
        print("未初始化：无 sync_state.json。先运行 init --source <path|url>")
        return 0
    src = resolve_src(state)
    assert_not_self(src)
    head = _git(src, "rev-parse", "--short", "HEAD").stdout.strip() or "?"
    dirty = src_dirty(src)
    prompts = active_prompts(state)

    print("## repo-template-sync 预览")
    print(f"\nSRC: {state['template_source']['value']} @ {head}  dirty={dirty}")
    print("\n### 站立指令 user_prompts（裁定优先）")
    if prompts:
        rows = [[str(i), p.get("at", ""), p.get("text", "")] for i, p in enumerate(prompts)]
        print(_md_table(["#", "at", "text"], rows))
    else:
        print("无")

    print("\n### 强制覆盖（同步分类）")
    rows = []
    for item in hard_sync_status(src):
        if item["state"] != "same":
            rows.append([item["rel"], item["state"], "树对树覆盖" if item["state"] == "write" else "删除"])
    for item in skill_status(src):
        if item["action"] == "override":
            rows.append([f".repo_template/skills/{item['name']}", "both_differ", "强制覆盖（含 front matter）"])
        elif item["action"] == "stale":
            rows.append([f".agents/skills/{item['name']}", "stale_dir", "旧真实目录转软链（备份原内容）"])
        elif item["action"] == "keep":
            rows.append([f".agents/skills/{item['name']}", "consumer_only", "保留（禁止删）"])
    print(_md_table(["单元", "分类", "处置"], rows))

    print("\n### 裁定同步 — 逐项（有 diff 必出现）")
    rows = []
    blocked = prompt_substrings(state)
    agents_is_sectioned = agents_section_status(src) is not None
    for item in shared_status(src):
        if item["unit"] == "AGENTS.md" and agents_is_sectioned:
            continue
        if item["cls"] == "both_identical":
            continue
        if item["unit"] == ".gitignore" and item["cls"] in ("both_differ", "template_only"):
            disp = "merge_into_consumer" + ("（遵从 prompt 拦截）" if blocked else "")
        elif item["cls"] == "template_only":
            disp = "建议 update_from_template"
        elif item["cls"] == "consumer_only":
            disp = "keep_consumer"
        else:
            disp = "ask_user / agent 决策"
        rows.append([item["unit"], item["cls"], disp])
    print(_md_table(["单元", "分类", "disposition"], rows))

    print("\n### AGENTS.md 分区")
    section_status = agents_section_status(src)
    if section_status is None:
        print("未识别到完整标题协议：需要 ## 目录与读写规则、## 开发原则")
    else:
        print(_md_table(["区段", "状态", "处置"], [
            ["项目介绍", section_status["intro"], "绝不更新，保留消费仓内容"],
            ["目录与读写规则", section_status["merge"], "agent 语义合并，脚本不覆盖"],
            ["开发原则", section_status["force"], "每轮强制从模板更新"],
        ]))

    print("\n### 软链")
    rows = []
    for item in symlink_status():
        mark = {"ok": "正确", "repair": "需建/修", "unmanaged": "非本机制，不碰"}[item["state"]]
        rows.append([f".claude/skills/{item['name']}", item["state"], mark])
    print(_md_table(["路径", "状态", "说明"], rows))

    print("\n### format 豁免（.prettierignore 机械合并）")
    dst = CONSUMER / ".prettierignore"
    existing = {ln.strip() for ln in dst.read_text(encoding="utf-8").splitlines()} if dst.exists() else set()
    missing = [r for r in PRETTIERIGNORE_TEMPLATE_RULES if r not in existing]
    if missing:
        rows = [[rule, "缺失", "apply 追加"] for rule in missing]
        print(_md_table(["规则", "状态", "处置"], rows))
    else:
        print("齐全（模板自有路径已豁免）")
    for warning in retired_template_warnings():
        print(f"- STALE: {warning}")

    print("\n### workflow schema 强制迁移")
    migrations, worktrees, migration_errors = workflow_migration_status(src)
    if migration_errors:
        print("BLOCKED：以下文档无法自动迁移：")
        for error in migration_errors:
            print(f"- {error}")
    if worktrees:
        print("BLOCKED：先完成或 rewind 已登记 task worktree：")
        for root, branch in worktrees:
            print(f"- {branch} @ {root}")
    if migrations:
        for path in migrations:
            print(f"- {path}")
    if not migration_errors and not worktrees and not migrations:
        print("无")

    print("\n### state 推进预期")
    if dirty:
        print(f"SRC dirty，apply 可写盘但**不**推进 last_synced_commit")
    else:
        print(f"apply 通过后推进 last_synced_commit -> {head}")
    return 0


def _apply_sync_write(src: Path, decisions: dict[str, str], changed: set[Path], blocked: list[str]) -> None:
    """apply 的写盘主体；OSError 由调用方回滚（F16）。"""
    for rel in HARD_SYNC_DIRS:
        s, d = src / rel, CONSUMER / rel
        if s.exists():
            sync_dir(s, d, changed)
        elif d.exists():
            _stage_rollback(d)
            shutil.rmtree(d)
            changed.add(d)
    for rel in HARD_SYNC_FILES:
        sync_file(src / rel, CONSUMER / rel, changed)

    for report in force_migrate_workflow_tasks(changed):
        print(f"提示: {report}")
    reports = repair_symlinks(changed)
    for r in reports:
        print(f"提示: {r}")
    for r in sync_opencode_commands(changed):
        print(f"提示: {r}")

    if (src / ".gitignore").exists():
        info = merge_gitignore(src, blocked, changed)
        if info["added"]:
            print(f".gitignore 追加 {len(info['added'])} 条（模板独有）")
        if info["removed"]:
            print(f".gitignore 删除 {len(info['removed'])} 条（prompt 禁止 ignore）")
    prettier_info = merge_prettierignore(changed)
    if prettier_info["added"]:
        print(f".prettierignore 追加 {len(prettier_info['added'])} 条（模板自有路径豁免 prettier）")
    for warning in retired_template_warnings():
        print(f"提示: {warning}")
    merge_mcp(src, changed)

    for unit in SHARED_FILES:
        if unit == ".gitignore":
            continue
        decision = decisions.get(unit)
        _apply_shared_unit(unit, decision, src, changed)


def cmd_apply(args: argparse.Namespace) -> int:
    state = read_state()
    if not state:
        raise SyncError("未初始化：无 sync_state.json。先运行 init --source <path|url>")
    src = resolve_src(state)
    assert_not_self(src)
    decisions = getattr(args, "decisions", None) or {}
    changed: set[Path] = set()
    blocked = prompt_substrings(state)

    try:
        _apply_sync_write(src, decisions, changed, blocked)
    except (OSError, SyncError) as error:
        _rollback_changes()
        raise SyncError(f"apply 中途失败，已回滚已覆盖文件（{error}）") from error

    if not args.skip_tests:
        if not _run_tests(CONSUMER):
            print("pytest .repo_template/tests/ -m contract 失败，不推进 state", file=sys.stderr)
            _cleanup_rollback()
            return 1
    else:
        print("跳过测试验证（--skip-tests）")

    dirty = src_dirty(src)
    if not dirty:
        head = _git(src, "rev-parse", "HEAD").stdout.strip()
        state["last_synced_commit"] = head
    state["last_synced_at"] = _now_iso()
    write_state(state)

    print("\n=== 改动路径清单（commit 门禁点名 add）===")
    for path in sorted(changed, key=str):
        print(_rel(path))
    if not changed:
        print("（无改动）")
    print(f"\nstate 推进：last_synced_commit={'已更新' if not dirty else 'SRC dirty，未推进'}, "
          f"last_synced_at={state['last_synced_at']}")
    _cleanup_rollback()
    return 0


def cmd_prompt(args: argparse.Namespace) -> int:
    state = read_state()
    if not state:
        raise SyncError("未初始化：无 sync_state.json。先运行 init --source <path|url>")
    if args.action == "list":
        for i, p in enumerate(state.get("user_prompts", [])):
            rev = " [revoked]" if p.get("revoked") else ""
            print(f"#{i}{rev} {p.get('at')} tags={p.get('tags', [])} {p.get('text')}")
        return 0
    prompts = state.setdefault("user_prompts", [])
    if args.action == "add":
        if not args.text:
            raise SyncError("prompt add 需要 --text")
        tags = [t.strip().lower() for t in (args.tags or "").split(",") if t.strip()]
        for p in prompts:
            if p.get("revoked"):
                continue
            old_tags = {str(t).lower() for t in p.get("tags", [])}
            if old_tags & set(tags):
                p["revoked"] = True
        prompts.append({"at": _now_iso(), "text": args.text, "tags": tags, "revoked": False})
        write_state(state)
        print(f"已登记 prompt #{len(prompts) - 1}: {args.text}")
        return 0
    if args.action == "revoke":
        idx = args.id
        if idx is None or not (0 <= idx < len(prompts)):
            raise SyncError(f"revoke 需要合法 --id（0..{len(prompts) - 1}）")
        prompts[idx]["revoked"] = True
        write_state(state)
        print(f"已作废 prompt #{idx}")
        return 0
    return 0


def cmd_prep(args: argparse.Namespace) -> int:
    """同步工具自举：单向覆盖（新增+覆盖，不删除）core skill 与 .repo_template/scripts，并建软链。

    由 repo-template-sync 启动器在每轮同步前调用，保证随后执行的 core skill 与脚本能力
    为模板源最新版。不写 state（不推进 last_synced_*）。
    """
    state = read_state()
    if not state:
        raise SyncError("未初始化：无 sync_state.json。先运行 init --source <path|url>")
    src = resolve_src(state)
    assert_not_self(src)
    changed: set[Path] = set()

    src_tool = src / ".repo_template/scripts"
    if src_tool.exists():
        sync_dir_oneway(src_tool, CONSUMER / ".repo_template/scripts", changed)

    src_core = src / ".repo_template/skills/repo-template-sync-core"
    if src_core.exists():
        sync_skill(src_core, SKILLS_SRC / "repo-template-sync-core", changed)

    reports = repair_symlinks(changed)
    for r in reports:
        print(f"提示: {r}")
    for r in sync_opencode_commands(changed):
        print(f"提示: {r}")

    print("=== prep 改动路径清单（单向覆盖，未删除）===")
    for path in sorted(changed, key=str):
        print(_rel(path))
    if not changed:
        print("（工具已是最新，无改动）")
    return 0


def cmd_install_hooks(args: argparse.Namespace) -> int:
    """幂等设置 core.hooksPath 指向工具链 hooks。

    git 对相对路径按仓库顶层解析。消费仓 hooks 在 `.repo_template/hooks`；
    工厂仓产物在 `repo/` 下时须写成 `repo/.repo_template/hooks`。已有其它
    hooksPath 时拒绝，须 --force。
    """
    hooks_dir = CONSUMER / ".repo_template" / "hooks"
    hook_script = hooks_dir / "pre-commit"
    if not hook_script.is_file():
        print("错误: 缺 hook 脚本 .repo_template/hooks/pre-commit", file=sys.stderr)
        return 1
    if not os.access(hook_script, os.X_OK):
        print("错误: .repo_template/hooks/pre-commit 不可执行", file=sys.stderr)
        return 1
    toplevel = _git(CONSUMER, "rev-parse", "--show-toplevel").stdout.strip()
    if not toplevel:
        print("错误: 无法解析 git 仓库顶层", file=sys.stderr)
        return 1
    try:
        hooks_rel = hooks_dir.resolve().relative_to(Path(toplevel).resolve()).as_posix()
    except ValueError:
        print(
            f"错误: hooks 目录不在仓库顶层内：{hooks_dir} / {toplevel}",
            file=sys.stderr,
        )
        return 1
    current = _git(CONSUMER, "config", "--get", "core.hooksPath").stdout.strip()
    if current == hooks_rel:
        print(f"core.hooksPath 已指向 {hooks_rel}，无需改动")
        return 0
    if current and not getattr(args, "force", False):
        print(
            f"错误: core.hooksPath 已是 {current}；"
            f"覆盖为 {hooks_rel} 须加 --force",
            file=sys.stderr,
        )
        return 1
    result = _git(CONSUMER, "config", "core.hooksPath", hooks_rel)
    if result.returncode != 0:
        print(f"错误: 设置 core.hooksPath 失败：{result.stderr.strip()}", file=sys.stderr)
        return 1
    print(f"core.hooksPath 已设为 {hooks_rel}")
    return 0


